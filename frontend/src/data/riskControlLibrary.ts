// 从已勾选的风险清单智能匹配控制措施（去重 + 标记共用来源）
export function matchControls(checkedRiskTexts: string[]): MatchedControl[] {
  const map = new Map<string, { text: string; sources: string[]; checked: boolean }>();
  for (const risk of checkedRiskTexts) {
    const controls = RISK_TO_CONTROLS[risk] || [];
    for (const c of controls) {
      const hit = map.get(c);
      if (hit) {
        if (!hit.sources.includes(risk)) hit.sources.push(risk);
      } else {
        map.set(c, { text: c, sources: [risk], checked: true });
      }
    }
  }
  return [...map.values()];
}
